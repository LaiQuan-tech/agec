-- ============================================================
-- 消息的學制標記 news.program（招生消息分學制）
--
-- 客戶回饋（2026-09）：
--   ④ 招生資訊頁四張學制卡的「查看招生資訊」全部連到最新消息的招生區塊，
--      無法區分學制，希望各自有對應的資訊頁（招生資訊獨立出最新消息）。
--   ③ 當年度招生簡章、書面資料、考古題要能分別顯示四個學制各自的資訊。
--
-- 舊站（agec.ntu.edu.tw）的「招生資訊」本來就是四頁：大學部招生／碩士班招生／
-- 博士班招生／碩士在職專班（/zh_tw/recruit/recruit1–4），每一頁是該學制的招生
-- 公告清單。新站 2026-08-31 搬進來的 156 則招生消息，用舊站的文章 id 逐一比對
-- 舊站四頁的清單，**每一則都對得到學制**（大學部 33／碩士班 20／博士班 33／
-- 碩士在職專班 54／國際專班 16）。
--
-- 所以做法是：news 加 `program` 欄（值同 programs.name 的中文原值，與
-- links.program、documents.program 同一個約定；null = 不分學制），一次把 156 則
-- 標好；新頁 /admissions/[program] 列出該學制的招生公告（category='招生' 且
-- program=該學制）＋標了學制的檔案與連結。後台新增消息時多一個「學制」下拉。
--
-- 「國際專班」不在 programs 表裡（新站四個學制沒有它），那 16 則照樣標上，
-- 只是沒有對應的頁；後台的下拉會顯示成「已不在學制清單中」，不會被清掉。
--
-- 順手：links 表 id 23–25 那三張「當年度招生簡章／書面資料格式／考古題專區」
-- 卡片（2026-08 種子，網址指向舊站的 recruit1、一則舊站公告與 link5）刪掉 ——
-- /admissions §4 改成三張固定的學制入口卡（程式裡），它們的角色被取代了。
-- 原網址留在這裡備查：
--   23 當年度招生簡章  https://www.agec.ntu.edu.tw/zh_tw/recruit/recruit1
--   24 書面資料格式    https://www.agec.ntu.edu.tw/zh_tw/recruit/recruit1/-招生-115學年度申請入學-書面資料表格下載-55855145
--   25 考古題專區      https://www.agec.ntu.edu.tw/zh_tw/link/link5
--
-- 🔴 **必須在推程式碼之前跑。** lib/data.ts 的 NEWS_COLUMNS 是逐一列欄位的字串，
--    欄位不存在時 PostgREST 回錯誤、每一支 news getter 回空 —— 首頁與 /news 整個
--    空掉。
--
-- ⚠️ 這個專案沒有 Supabase CLI，migration 是人工貼進 Dashboard SQL Editor
--    （或 Management API）。跑完請回 supabase/README.md 勾記。
--
-- 可重複執行（加欄 if not exists；標記只補 null；刪除以 id＋label 雙重比對）。
-- ============================================================

alter table public.news
  add column if not exists program text;

